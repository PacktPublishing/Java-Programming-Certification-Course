class Demo41 {
    public static void main(String[] args) {

        int marks = 60;

        switch (marks) {
            case 90:
                System.out.println("Grade A");
                break;
            case 75:
                System.out.println("Grade B");
                break;
            case 60:
                System.out.println("Grade C");
                break;
            case 50:
                System.out.println("Grade D");
                break;
        }
    }
}