class Demo11 {
    public static void main(String[] args) {

        int a, b, c;
        a = 50;
        b = 100;
        c = 150;

        System.out.println("Value of a+b = "+(a+b));
        System.out.println("Value of b-a = "+(b-a));
        System.out.println("Value of c/a = "+(c/a));
        System.out.println("Value of a*b = "+(a*b));
        System.out.println("Value of c%b = "+(c%b));
    }
}