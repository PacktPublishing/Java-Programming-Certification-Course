public class Demo13 {

    public static void main(String[] args) {

        int a, b, c;
        a = 5;
        b = 10;
        c = 15;

        System.out.println("Value of a == b is " + (a == b ));
        System.out.println("Value of a != b is " + (a != b ));
        System.out.println("Value of b > c is " + (b > c ));
        System.out.println("Value of c < a is " + (c < a ));
        System.out.println("Value of c >= b is " + (c >= b ));
        System.out.println("Value of b <= c is " + (b <= c ));
    }
}
